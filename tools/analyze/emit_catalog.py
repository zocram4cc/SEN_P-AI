#!/usr/bin/env python3
"""Measurement YAML -> src/catalogs/<Tag>Stats.cpp (spec 4.5). CLI: emit_catalog.py YAML"""
import sys

import yaml

VIS = {"DontCare", "Normal", "Important", "Unknown"}


def emit(path):
    spec = yaml.safe_load(open(path))
    tag, rows = spec["tag"], spec["stats"]
    lines = [f"// Generated by tools/analyze/emit_catalog.py from {path} - do not edit.",
             '#include "../StatsInfo.h"',
             "#define DontCare false, false", "#define Normal true, false",
             "#define Important true, true", "#define Unknown false, true",
             "#define L QStringLiteral",
             f"PESstat {tag}Stats[{len(rows)}] = {{"]
    for i, s in enumerate(rows):
        off = s["offset"]
        vis = s["vis"] if off != -1 else "false, false"
        if off != -1 and vis not in VIS:
            raise ValueError(f"{s['name']}: vis {vis!r}")
        off_text = "-1" if off == -1 else f"0x{off:04X}"
        lines.append(f'    {{{i:3}, {off_text}, {s["type"]},{s["count"]},  L("{s["name"]}"), {vis}}},'
                     f'  // {s["evidence"]}')
    lines += ["};", f"const size_t {tag}StatCount = {len(rows)};",
              f"const size_t {tag}EntrySize = {spec['entry_size']};", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    sys.stdout.write(emit(sys.argv[1]))
